import React, { useState } from 'react';
import { Head, useForm } from '@inertiajs/react';
import { Shield, Key, ArrowRight, Smartphone } from 'lucide-react';
import ApplicationLogo from '@/Components/ApplicationLogo';

export default function TwoFactorChallenge() {
    const [recovery, setRecovery] = useState(false);

    const { data, setData, post, processing, errors, reset } = useForm({
        code: '',
        recovery_code: '',
    });

    const handleSubmit = (e: React.FormEvent) => {
        e.preventDefault();
        post('/two-factor-challenge', {
            onFinish: () => reset(),
        });
    };

    const toggleRecovery = () => {
        setRecovery(!recovery);
        setData({ code: '', recovery_code: '' });
    };

    return (
        <div className="min-h-screen bg-slate-50 dark:bg-slate-950 text-slate-900 dark:text-slate-100 flex flex-col justify-center py-12 sm:px-6 lg:px-8 relative selection:bg-indigo-500/20 selection:text-indigo-600">
            <Head title="Two-Factor Authentication Challenge — MedVisit" />

            {/* Ambient Background Glows */}
            <div aria-hidden="true" className="fixed inset-0 pointer-events-none -z-10 overflow-hidden">
                <div className="absolute top-1/4 left-1/3 w-96 h-96 rounded-full bg-indigo-500/10 dark:bg-indigo-500/15 blur-3xl" />
            </div>

            <div className="sm:mx-auto sm:w-full sm:max-w-md text-center">
                <div className="inline-flex items-center justify-center w-14 h-14 rounded-2xl bg-indigo-600 text-white shadow-lg shadow-indigo-600/30 mb-4">
                    <Shield className="w-8 h-8" />
                </div>
                <h2 className="text-2xl font-bold tracking-tight text-slate-900 dark:text-white">
                    Two-Factor Authentication
                </h2>
                <p className="mt-2 text-xs sm:text-sm text-slate-500 dark:text-slate-400">
                    {recovery
                        ? 'Please enter one of your emergency recovery codes to complete authentication.'
                        : 'Confirm access by entering the 6-digit authentication code generated by your mobile app.'}
                </p>
            </div>

            <div className="mt-8 sm:mx-auto sm:w-full sm:max-w-md px-4 sm:px-0">
                <div className="bg-white/80 dark:bg-slate-900/80 backdrop-blur-2xl py-8 px-6 sm:px-10 shadow-2xl rounded-3xl border border-slate-200/80 dark:border-white/10">
                    <form onSubmit={handleSubmit} className="space-y-5">
                        {!recovery ? (
                            <div>
                                <label className="block text-xs font-bold text-slate-700 dark:text-slate-300 mb-2 text-center">
                                    6-Digit Authenticator Code
                                </label>
                                <input
                                    type="text"
                                    inputMode="numeric"
                                    autoFocus
                                    maxLength={6}
                                    value={data.code}
                                    onChange={(e) => setData('code', e.target.value)}
                                    placeholder="123456"
                                    className="w-full text-center tracking-widest font-mono text-2xl py-2.5 rounded-2xl border border-slate-200 dark:border-white/10 bg-white/70 dark:bg-slate-800/70 text-slate-900 dark:text-white focus:ring-2 focus:ring-indigo-500 shadow-xs"
                                    required
                                />
                            </div>
                        ) : (
                            <div>
                                <label className="block text-xs font-bold text-slate-700 dark:text-slate-300 mb-2 text-center">
                                    Emergency Recovery Code
                                </label>
                                <input
                                    type="text"
                                    autoFocus
                                    value={data.recovery_code}
                                    onChange={(e) => setData('recovery_code', e.target.value)}
                                    placeholder="xxxxx-xxxxx"
                                    className="w-full text-center tracking-widest font-mono text-lg py-2.5 rounded-2xl border border-slate-200 dark:border-white/10 bg-white/70 dark:bg-slate-800/70 text-slate-900 dark:text-white focus:ring-2 focus:ring-indigo-500 shadow-xs"
                                    required
                                />
                            </div>
                        )}

                        {errors.code && (
                            <div className="p-3 rounded-xl bg-rose-500/10 border border-rose-500/20 text-rose-600 dark:text-rose-400 text-xs font-medium text-center">
                                {errors.code}
                            </div>
                        )}

                        <button
                            type="submit"
                            disabled={processing}
                            className="w-full py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white font-bold text-xs sm:text-sm shadow-md shadow-indigo-600/20 transition-all flex items-center justify-center gap-2 cursor-pointer"
                        >
                            <span>Verify and Continue</span>
                            <ArrowRight className="w-4 h-4" />
                        </button>

                        <div className="text-center pt-2">
                            <button
                                type="button"
                                onClick={toggleRecovery}
                                className="text-xs text-indigo-600 dark:text-indigo-400 hover:underline font-semibold"
                            >
                                {recovery
                                    ? 'Use authenticator app code instead'
                                    : 'Lost your device? Use an emergency recovery code'}
                            </button>
                        </div>
                    </form>
                </div>
            </div>
        </div>
    );
}
